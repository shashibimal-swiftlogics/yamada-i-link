// Generates lib/master-default.mjs: the built-in FICTIONAL master data (test data only).
// Run: node scripts/gen-master.mjs   (re-run only when the fictional fixtures are changed on purpose)
import { writeFileSync } from 'node:fs';
import { toCsv } from '../lib/csv.mjs';
import { TABLES } from '../lib/master.mjs';

const categories = ['麺類', 'だし・調味料', '具材', '野菜', '備品'];
const categoryLocation = { 麺類: 'LOC-FAC-01', 'だし・調味料': 'LOC-STK-01', 具材: 'LOC-FAC-01', 野菜: 'LOC-LOG-01', 備品: 'LOC-STK-02' };
const names = [
  ['うどん', '細うどん', 'そば', '中華麺', 'きしめん'],
  ['かけだし', 'つけだし', '醤油だれ', '味噌だれ', 'カレーだし'],
  ['油揚げ', 'かき揚げ', '海老天', 'とろろ', '温泉卵'],
  ['ねぎ', 'ほうれん草', '玉ねぎ', 'にんじん', '白菜'],
  ['箸', 'おしぼり', '持帰り容器', '紙ナプキン', '手袋'],
];
const sizes = ['標準', '小分け', '業務用', '徳用'];

const locations = [
  ['LOC-FAC-01', 'テスト工場（架空）', 'factory'],
  ['LOC-STK-01', '常温倉庫（架空）', 'stock_room'],
  ['LOC-STK-02', '備品倉庫（架空）', 'stock_room'],
  ['LOC-LOG-01', '配送センター（架空）', 'logistics'],
];

const products = Array.from({ length: 100 }, (_, i) => {
  const group = Math.floor(i / 20);
  const category = categories[group];
  return [
    `P${String(i + 1).padStart(3, '0')}`,
    `${names[group][i % 5]} ${sizes[Math.floor((i % 20) / 5)]}`,
    category,
    group === 4 ? '1箱' : '1パック',
    200 + ((i % 17) * 80),
    categoryLocation[category],
    1,
  ];
});

// 150 fictional shop accounts. Routes are assigned in blocks of 30.
const shops = Array.from({ length: 150 }, (_, i) => [
  `S${String(i + 1).padStart(3, '0')}`,
  `テスト店舗${String(i + 1).padStart(3, '0')}（架空）`,
  `R${Math.floor(i / 30) + 1}`,
  'LOC-LOG-01',
  1,
]);

const csv = {
  locations: toCsv(TABLES.locations.columns, locations),
  products: toCsv(TABLES.products.columns, products),
  shops: toCsv(TABLES.shops.columns, shops),
};

writeFileSync(
  new URL('../lib/master-default.mjs', import.meta.url),
  `// GENERATED by scripts/gen-master.mjs. Fictional test data only. Do not use for real operations.\nexport const defaultMasterCsv = ${JSON.stringify(csv, null, 1)};\n`,
);
console.log(`locations ${locations.length}, products ${products.length}, shops ${shops.length}`);
